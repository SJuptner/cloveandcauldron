// Runs as part of `dev`/`build` (see package.json) -- reads the JSON-LD
// logo PNG's dimensions off disk and writes them out as a source file.
// This exists so lib/seo.ts never needs fs access at runtime: reading
// public/ via fs.readFileSync works during `next build` and `next dev`
// (full local filesystem) but throws ENOENT in Vercel's serverless
// functions, whose bundles only include files Next's static import
// tracing can see -- a dynamically-built fs.readFileSync path is invisible
// to that tracing. Computing the value here, once, and importing it as a
// plain constant sidesteps the problem entirely.
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const rootDir = path.dirname(fileURLToPath(import.meta.url)) + '/..';
const LOGO_PUBLIC_PATH = '/logo/icon-black.png';

function readPngDimensions(absolutePath) {
  const buffer = readFileSync(absolutePath);
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}

const { width, height } = readPngDimensions(path.join(rootDir, 'public', LOGO_PUBLIC_PATH));

const outDir = path.join(rootDir, 'lib', 'generated');
mkdirSync(outDir, { recursive: true });

const outFile = path.join(outDir, 'logo-meta.ts');
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-logo-meta.mjs -- do not edit by hand.
// Regenerated on every \`pnpm dev\` / \`pnpm build\`; re-run manually after
// swapping the logo asset if you need the values updated outside of that.
export const LOGO_PATH = ${JSON.stringify(LOGO_PUBLIC_PATH)};
export const LOGO_WIDTH = ${width};
export const LOGO_HEIGHT = ${height};
`
);

console.log(`[generate-logo-meta] ${LOGO_PUBLIC_PATH} is ${width}x${height} -> lib/generated/logo-meta.ts`);
